export const ALL_SECTIONS = BLOCKS.flatMap((b) => b.sections.map((s) => Object.assign(s, { blockId: b.id })))
export const SECTION_BY_ID = Object.fromEntries(ALL_SECTIONS.map((s) => [s.id, s]))
export const sectionItems = (section) => section.groups.flatMap((gr) => gr.items)

// Разделы, которые сводятся к уровню 0–3 (участвуют в динамике).
export const isScored = (section) => section.kind === 'scale' || section.kind === 'sound'
export const SPEECH_SECTIONS = BLOCKS[0].sections
export const NEURO_SCORED = BLOCKS[1].sections.filter(isScored)

export function optionsFor(section) {
  if (section.kind === 'scale') return SCALE.map((s) => ({ value: s.value, mark: String(s.value), label: s.label }))
  if (section.kind === 'sound') return SOUND_STATES
  if (section.kind === 'side') return SIDE_OPTIONS
  if (section.kind === 'yesno') return YESNO_OPTIONS
  return SCAN_OPTIONS
}

